import { useId, useState } from 'react';
import { useFieldArray, useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { useQueryClient } from '@tanstack/react-query';
import {
  CircleAlertIcon,
  CircleCheckIcon,
  ImagePlusIcon,
  Loader2Icon,
  Trash2Icon,
} from 'lucide-react';
import { puzzleKeys, savePuzzle, useApi } from '@/api/queries';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { Field, FieldDescription, FieldError, FieldLabel } from '@/components/ui/field';
import { Input } from '@/components/ui/input';
import { mapWithConcurrency } from '@/lib/mapWithConcurrency';
import { readPhotoDate } from '@/lib/photoDate';
import {
  bulkFormSchema,
  bulkItemToInput,
  MAX_BULK_PHOTOS,
  newBulkItem,
  type BulkFormValues,
} from './bulkForm';
import { PhotoPreview } from './PhotoPreview';

/** Uploads at once: fast on a good connection without saturating a phone's. */
const CONCURRENT_SAVES = 3;

type RowStatus = { state: 'saving' } | { state: 'saved' } | { state: 'error'; message: string };

export interface BulkSaveResult {
  saved: number;
  failed: number;
}

/**
 * Add many puzzles from many photos. Each photo becomes a row (`useFieldArray`) with the
 * date pre-filled from its EXIF data, so usually only the title needs typing.
 *
 * Saving runs `CONCURRENT_SAVES` uploads at a time and tracks each row's status. Rows that
 * saved are kept (and skipped on retry) so a partial failure never creates duplicates.
 */
export function BulkAddForm({ onDone }: { onDone: (result: BulkSaveResult) => void }) {
  const api = useApi();
  const queryClient = useQueryClient();
  const pickerId = useId();

  const {
    control,
    register,
    handleSubmit,
    getValues,
    setValue,
    formState: { errors, isSubmitting },
  } = useForm<BulkFormValues>({
    resolver: zodResolver(bulkFormSchema),
    defaultValues: { items: [] },
  });
  // `fields[i].id` is a stable key generated by React Hook Form, so row state (statuses)
  // follows the right row even after others are removed.
  const { fields, append, remove } = useFieldArray({ control, name: 'items' });

  const [statuses, setStatuses] = useState<Record<string, RowStatus>>({});
  const [photoDates, setPhotoDates] = useState<Set<File>>(new Set());
  const isSaved = (id: string) => statuses[id]?.state === 'saved';

  function setStatus(id: string, status: RowStatus) {
    setStatuses((current) => ({ ...current, [id]: status }));
  }

  function addPhotos(files: File[]) {
    const room = MAX_BULK_PHOTOS - fields.length;
    const images = files.filter((file) => file.type.startsWith('image/')).slice(0, room);
    append(images.map(newBulkItem));
    // Fill each row's date from its photo once read. Look the row up by its file, since
    // rows may have been removed or reordered by the time the read finishes.
    for (const photo of images) {
      void readPhotoDate(photo).then((date) => {
        const index = getValues('items').findIndex((item) => item.photo === photo);
        if (date && index !== -1 && !getValues(`items.${index}.completedAt`)) {
          setValue(`items.${index}.completedAt`, date);
          setPhotoDates((current) => new Set(current).add(photo));
        }
      });
    }
  }

  // Rebuilt every render, so `statuses` here is current when Save is tapped.
  const save = handleSubmit(async ({ items }) => {
    const toSave = fields
      .map((field, index) => ({ id: field.id, item: items[index]! }))
      .filter(({ id }) => !isSaved(id));
    let saved = 0;

    await mapWithConcurrency(toSave, CONCURRENT_SAVES, async ({ id, item }) => {
      setStatus(id, { state: 'saving' });
      try {
        await savePuzzle(api, { input: bulkItemToInput(item), photo: item.photo });
        saved++;
        setStatus(id, { state: 'saved' });
      } catch (error) {
        setStatus(id, {
          state: 'error',
          message: error instanceof Error ? error.message : 'Could not save',
        });
      }
    });

    // One refresh for the whole batch instead of one per puzzle.
    await queryClient.invalidateQueries({ queryKey: puzzleKeys.all });
    onDone({ saved, failed: toSave.length - saved });
  });

  const unsaved = fields.filter((field) => !isSaved(field.id)).length;

  return (
    <form onSubmit={save} noValidate className="space-y-4">
      {fields.length < MAX_BULK_PHOTOS && (
        <label
          htmlFor={pickerId}
          className="flex cursor-pointer items-center justify-center gap-2 rounded-xl border-2 border-dashed p-4 text-muted-foreground transition-colors hover:bg-muted/50"
        >
          <ImagePlusIcon className="size-5" aria-hidden />
          <span className="text-sm">
            {fields.length === 0 ? 'Choose photos' : 'Add more photos'}
          </span>
        </label>
      )}
      <input
        id={pickerId}
        type="file"
        accept="image/*"
        multiple
        className="sr-only"
        aria-label="Choose photos"
        disabled={isSubmitting}
        onChange={(event) => {
          addPhotos([...(event.target.files ?? [])]);
          event.target.value = '';
        }}
      />
      <FieldError errors={[errors.items?.root, errors.items]} />

      <ol className="space-y-3">
        {fields.map((field, index) => {
          const status = statuses[field.id];
          const locked = isSubmitting || isSaved(field.id);
          const itemErrors = errors.items?.[index];
          const photo = getValues(`items.${index}.photo`);
          const label = `photo ${index + 1}`;
          return (
            <li key={field.id}>
              <Card role="group" className="flex-row gap-3 p-3" aria-label={`Puzzle ${index + 1}`}>
                <div className="flex shrink-0 flex-col items-center gap-1">
                  <PhotoPreview
                    file={photo}
                    alt={`Puzzle ${label}`}
                    className="size-16 rounded-lg"
                  />
                  {!locked && (
                    <Button
                      type="button"
                      variant="ghost"
                      size="icon-sm"
                      onClick={() => remove(index)}
                      aria-label={`Remove ${label}`}
                    >
                      <Trash2Icon />
                    </Button>
                  )}
                </div>
                <fieldset disabled={locked} className="min-w-0 flex-1 space-y-2">
                  <Field data-invalid={!!itemErrors?.title}>
                    <FieldLabel htmlFor={`${field.id}-title`} className="sr-only">
                      Title for {label}
                    </FieldLabel>
                    <Input
                      id={`${field.id}-title`}
                      placeholder="Title"
                      autoComplete="off"
                      aria-invalid={!!itemErrors?.title}
                      {...register(`items.${index}.title`)}
                    />
                    <FieldError errors={[itemErrors?.title]} />
                  </Field>
                  <div className="grid grid-cols-[5.5rem_1fr] gap-2">
                    <Field data-invalid={!!itemErrors?.pieceCount} className="min-w-0">
                      <FieldLabel htmlFor={`${field.id}-pieces`} className="sr-only">
                        Pieces for {label}
                      </FieldLabel>
                      <Input
                        id={`${field.id}-pieces`}
                        inputMode="numeric"
                        placeholder="Pieces"
                        aria-invalid={!!itemErrors?.pieceCount}
                        {...register(`items.${index}.pieceCount`)}
                      />
                      <FieldError errors={[itemErrors?.pieceCount]} />
                    </Field>
                    <Field className="min-w-0">
                      <FieldLabel htmlFor={`${field.id}-date`} className="sr-only">
                        Finished on for {label}
                      </FieldLabel>
                      <Input
                        id={`${field.id}-date`}
                        type="date"
                        className="min-w-0"
                        {...register(`items.${index}.completedAt`, {
                          onChange: () =>
                            setPhotoDates((current) => {
                              const next = new Set(current);
                              next.delete(photo);
                              return next;
                            }),
                        })}
                      />
                      {photoDates.has(photo) && (
                        <FieldDescription className="text-xs">From photo</FieldDescription>
                      )}
                    </Field>
                  </div>
                  <RowStatusLine status={status} />
                </fieldset>
              </Card>
            </li>
          );
        })}
      </ol>

      {fields.length > 0 && (
        <Button type="submit" size="lg" className="w-full" disabled={isSubmitting || !unsaved}>
          {isSubmitting && <Loader2Icon className="animate-spin" aria-hidden />}
          {isSubmitting ? 'Saving…' : `Save ${unsaved} ${unsaved === 1 ? 'puzzle' : 'puzzles'}`}
        </Button>
      )}
    </form>
  );
}

function RowStatusLine({ status }: { status?: RowStatus }) {
  if (!status) return null;
  if (status.state === 'saving') {
    return (
      <p className="flex items-center gap-1.5 text-sm text-muted-foreground">
        <Loader2Icon className="size-4 animate-spin" aria-hidden /> Saving…
      </p>
    );
  }
  if (status.state === 'saved') {
    return (
      <p className="flex items-center gap-1.5 text-sm text-emerald-600 dark:text-emerald-400">
        <CircleCheckIcon className="size-4" aria-hidden /> Saved
      </p>
    );
  }
  return (
    <p role="alert" className="flex items-center gap-1.5 text-sm text-destructive">
      <CircleAlertIcon className="size-4" aria-hidden /> {status.message}
    </p>
  );
}
